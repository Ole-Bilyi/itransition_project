DROP TABLE IF EXISTS DimDate;
CREATE TABLE DimDate AS SELECT
CONVERT(DATE, DateDay) AS date_key,
YEAR(DateDay) AS year,
MONTH(DateDay) AS month,
DAY(DateDay) AS day,
CAST(DATENAME(WEEKDAY, DateDay) AS VARCHAR(30)) AS day_name
FROM (SELECT DATEADD(DAY, value, '2025-01-01') AS DateDay
FROM GENERATE_SERIES(0, DATEDIFF(DAY, '2025-01-01', '2025-12-31'))) AS dates;
SELECT * FROM DimDate;